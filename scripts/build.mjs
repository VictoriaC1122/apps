import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFile(resolve(root, path), 'utf8');
const json = async path => JSON.parse(await read(path));
const digest = text => createHash('sha256').update(text).digest('hex').slice(0, 12);
const preview = process.argv.includes('--preview');
const languages = await json('data/languages.json');
const catalog = await json('data/catalog.json');
const source = await json('data/messages.json');
const uiKeys = Object.keys(source.ui);
const appIds = catalog.map(app => app.id);
const fields = ['title', 'description', 'highlight'];
const sameKeys = (value, keys) => value && !Array.isArray(value) && Object.keys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key));
const plainText = value => typeof value === 'string' && value.trim() && !/[<>]/.test(value);

if (languages.length !== 50 || new Set(languages.map(l => l.code)).size !== 50) throw new Error('Expected the same 50 unique locales as FireSparkle.Studio');
if (new Set(appIds).size !== appIds.length || !sameKeys(source.apps, appIds)) throw new Error('Catalog IDs and message IDs must match');
for (const app of catalog) {
  if (!/^\d+$/.test(app.id) || !['released', 'pending'].includes(app.status)) throw new Error(`Invalid catalog entry: ${app.id}`);
  await readFile(resolve(root, app.icon));
  for (const link of Object.values(app.url)) {
    const url = new URL(link);
    if (url.protocol !== 'https:' || url.hostname !== 'apps.apple.com' || !url.pathname.endsWith(`id${app.id}`)) throw new Error(`Invalid App Store link: ${app.id}`);
  }
}

function validate(payload, code) {
  if (!sameKeys(payload.ui, uiKeys) || !sameKeys(payload.apps, appIds)) throw new Error(`${code}: missing or unexpected UI/app keys`);
  if (!Object.values(payload.ui).every(plainText)) throw new Error(`${code}: UI must be nonempty plain text`);
  for (const id of appIds) {
    if (!sameKeys(payload.apps[id], fields) || !Object.values(payload.apps[id]).every(plainText)) throw new Error(`${code}: incomplete app ${id}`);
  }
}

const fromSource = lang => ({
  ui: Object.fromEntries(uiKeys.map(key => [key, source.ui[key][lang]])),
  apps: Object.fromEntries(appIds.map(id => [id, Object.fromEntries(fields.map(key => [key, source.apps[id][key][lang]]))])),
});
const dictionaries = [];
for (const language of languages) {
  try {
    const messages = ['zh-Hant', 'en'].includes(language.code) ? fromSource(language.code === 'en' ? 'en' : 'zh') : await json(`data/locales/${language.code}.json`);
    validate(messages, language.code);
    const payload = { locale: language.code, ...messages };
    const data = JSON.stringify(payload) + '\n';
    dictionaries.push({ ...language, file: `${language.code}.${digest(data)}.json`, data, payload });
  } catch (error) {
    if (!preview) throw error;
    console.warn(`Preview omitted ${language.code}: ${error.message}`);
  }
}
if (!preview && dictionaries.length !== 50) throw new Error('Publishing requires all 50 complete translations');
const defaultMessages = dictionaries.find(d => d.code === 'zh-Hant')?.payload;
if (!defaultMessages) throw new Error('Traditional Chinese fallback is required');
const publicLocales = dictionaries.map(({ data, payload, ...locale }) => locale);
const config = { complete: dictionaries.length === 50, locales: publicLocales, apps: catalog, uiKeys, defaultMessages };
await mkdir(resolve(root, 'locales'), { recursive: true });
for (const dictionary of dictionaries) await writeFile(resolve(root, 'locales', dictionary.file), dictionary.data);
// Only remove generated locale files owned by this builder; source translations stay in data/locales.
const keep = new Set(dictionaries.map(d => d.file));
for (const file of await readdir(resolve(root, 'locales'))) {
  if (/^[a-zA-Z-]+\.[a-f0-9]{12}\.json$/.test(file) && !keep.has(file)) await unlink(resolve(root, 'locales', file));
}
const configJS = `// Generated by scripts/build.mjs. Edit data/ instead.\nwindow.PORTFOLIO_CONFIG = ${JSON.stringify(config)};\n`;
await writeFile(resolve(root, 'i18n-config.js'), configJS);
let html = await read('src/index.html');
for (const [placeholder, file] of [['CONFIG_VERSION', 'i18n-config.js'], ['SCRIPT_VERSION', 'script.js'], ['STYLE_VERSION', 'styles.css']]) {
  html = html.replaceAll(`{{${placeholder}}}`, digest(await read(file)));
}
await writeFile(resolve(root, 'index.html'), html);
console.log(`Built ${catalog.length} apps in ${dictionaries.length} languages, ${uiKeys.length + appIds.length * fields.length} messages per language${preview ? ' (preview)' : ''}.`);
